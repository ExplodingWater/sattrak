#!/usr/bin/env python3
"""
GNC Visualization Engine
Parses flight telemetry CSV generated by mekf_adcs and produces analytical plots.
"""

import sys
import os
import math

def parse_telemetry(csv_path):
    if not os.path.exists(csv_path):
        print(f"Error: Telemetry file '{csv_path}' not found.")
        print("Run 'mekf_adcs' first to generate telemetry.")
        return None

    with open(csv_path, 'r') as f:
        lines = [line.strip() for line in f if line.strip()]

    if len(lines) < 2:
        print("Error: Empty or corrupted telemetry file.")
        return None

    header = lines[0].split(',')
    col_idx = {h: i for i, h in enumerate(header)}

    data = {h: [] for h in header}
    for line in lines[1:]:
        parts = line.split(',')
        if len(parts) != len(header):
            continue
        for h in header:
            data[h].append(float(parts[col_idx[h]]))

    return data

def print_ascii_dashboard(data):
    times = data['time']
    errs = data['att_error_deg']
    omega_x = data['omega_true_x']
    omega_y = data['omega_true_y']
    omega_z = data['omega_true_z']
    bias_est_x = data['bias_est_x']
    bias_true_x = data['bias_true_x']

    n = len(times)
    final_err = errs[-1]
    final_omega = math.sqrt(omega_x[-1]**2 + omega_y[-1]**2 + omega_z[-1]**2) * 180.0 / math.pi
    final_bias_err = abs(bias_est_x[-1] - bias_true_x[-1])

    print("\n" + "="*70)
    print("                 GNC / MEKF FLIGHT TELEMETRY SUMMARY")
    print("="*70)
    print(f"  Mission Duration Simulated   : {times[-1]:.2f} s ({n} telemetry frames)")
    print(f"  Initial Attitude Error        : {errs[0]:.2f} deg")
    print(f"  Final Attitude Error          : {final_err:.4f} deg")
    print(f"  Final Spacecraft Angular Rate : {final_omega:.4f} deg/s")
    print(f"  Final Gyro Bias Est Error (X) : {final_bias_err:.6f} rad/s")
    print(f"  3-Sigma Filter Attitude Bound : {data['att_3sig_x'][-1]*180.0/math.pi:.4f} deg")
    print("="*70)

    # ASCII sparkline / profile for attitude error convergence
    print("\n  Attitude Pointing Error Convergence (deg vs time):")
    sample_indices = [int(i * (n - 1) / 30) for i in range(31)]
    max_e = max(errs)
    height = 10
    grid = [[' ' for _ in range(31)] for _ in range(height)]

    for col, idx in enumerate(sample_indices):
        e = errs[idx]
        row = height - 1 - int((e / (max_e + 1e-6)) * (height - 1))
        row = max(0, min(height - 1, row))
        grid[row][col] = '*'

    for r in range(height):
        level = max_e * (height - 1 - r) / (height - 1)
        line = f"  {level:5.1f} | " + "".join(grid[r])
        print(line)
    print("        +" + "-"*31)
    print("        0 s" + " "*22 + f"{times[-1]:.0f} s\n")

def main():
    if len(sys.argv) > 1:
        csv_file = sys.argv[1]
    else:
        import glob
        adcs_files = sorted(glob.glob("data/adcs/*.csv"))
        csv_file = adcs_files[-1] if adcs_files else "telemetry_adcs.csv"

    print(f"Loading flight telemetry from: {csv_file}")
    data = parse_telemetry(csv_file)
    if not data:
        sys.exit(1)

    print_ascii_dashboard(data)

    # If matplotlib is available, generate PNG plot
    try:
        import matplotlib.pyplot as plt
        fig, axs = plt.subplots(2, 2, figsize=(14, 10))

        # Subplot 1: Attitude Error
        axs[0, 0].plot(data['time'], data['att_error_deg'], 'b-', lw=1.5, label='Attitude Error')
        axs[0, 0].axhline(0.1, color='r', linestyle='--', label='Pointing Threshold (0.1 deg)')
        axs[0, 0].set_ylabel('Pointing Error [deg]')
        axs[0, 0].set_title('3-Axis Closed-Loop Pointing Performance')
        axs[0, 0].grid(True)
        axs[0, 0].legend()

        # Subplot 2: Gyro Bias Estimation & 3-Sigma Bounds
        axs[0, 1].plot(data['time'], data['bias_true_x'], 'k--', label='True Bias X')
        axs[0, 1].plot(data['time'], data['bias_est_x'], 'r-', label='MEKF Est Bias X')
        upper = [est + sig for est, sig in zip(data['bias_est_x'], data['bias_3sig_x'])]
        lower = [est - sig for est, sig in zip(data['bias_est_x'], data['bias_3sig_x'])]
        axs[0, 1].fill_between(data['time'], lower, upper, color='red', alpha=0.2, label='3-Sigma Envelope')
        axs[0, 1].set_ylabel('Gyro Bias [rad/s]')
        axs[0, 1].set_title('MEKF Gyro Bias Tracking & Covariance Envelope')
        axs[0, 1].grid(True)
        axs[0, 1].legend()

        # Subplot 3: Spacecraft Angular Rates
        axs[1, 0].plot(data['time'], data['omega_true_x'], label='wx')
        axs[1, 0].plot(data['time'], data['omega_true_y'], label='wy')
        axs[1, 0].plot(data['time'], data['omega_true_z'], label='wz')
        axs[1, 0].set_xlabel('Time [s]')
        axs[1, 0].set_ylabel('Angular Velocity [rad/s]')
        axs[1, 0].set_title('Spacecraft Detumble & Angular Rates')
        axs[1, 0].grid(True)
        axs[1, 0].legend()

        # Subplot 4: Reaction Wheel Angular Momentum
        axs[1, 1].plot(data['time'], data['h_wheel_x'], label='Hx')
        axs[1, 1].plot(data['time'], data['h_wheel_y'], label='Hy')
        axs[1, 1].plot(data['time'], data['h_wheel_z'], label='Hz')
        axs[1, 1].set_xlabel('Time [s]')
        axs[1, 1].set_ylabel('Wheel Momentum [N*m*s]')
        axs[1, 1].set_title('Reaction Wheel Stored Angular Momentum')
        axs[1, 1].grid(True)
        axs[1, 1].legend()

        plt.tight_layout()
        plot_name = "adcs_performance_report.png"
        plt.savefig(plot_name, dpi=200)
        print(f"High-resolution performance plot saved to: {plot_name}")
    except ImportError:
        print("Note: matplotlib not installed in current Python environment. ASCII summary rendered above.")

if __name__ == "__main__":
    main()
